fails = 0
def check(name, cond):
    global fails
    print(("ok   " if cond else "FAIL ") + name)
    fails += 0 if cond else 1

# 1. parse the real Roudix file
blocks = core.parse_blocks(ROUDIX_HW)
check("roudix: 4 fileSystems blocks found", [b.mountpoint for b in blocks] == ["/", "/home", "/nix", "/boot"])
check("roudix: none adoptable (all protected)", not any(b.adoptable for b in blocks))
check("roudix: protected devices extracted", len(core.protected_devices(ROUDIX_HW)) == 4)
check("roudix: no entries", core.load_entries(ROUDIX_HW) == [])
check("roudix: no entries -> file unchanged", core.build_config(ROUDIX_HW, []) == ROUDIX_HW)

# 2. add entries, protected blocks stay byte-identical
e1 = core.MountEntry("/media/Data", "/dev/disk/by-uuid/aaaa-bbbb", "ext4", ["defaults", "nofail", "x-gvfs-show"])
e2 = core.MountEntry("/media/Games", "/dev/disk/by-uuid/1234", "btrfs", core.default_options("btrfs", False, 1000, 100))
out = core.build_config(ROUDIX_HW, [e1, e2])
for b in blocks:
    check(f"roudix: block {b.mountpoint} byte-identical", ROUDIX_HW[b.start:b.end] in out)
check("roudix: managed block before final brace", out.rstrip().endswith("# <<< roudix-disk\n}".rstrip()) or out.rstrip().endswith("}"))
check("roudix: round-trip entries", core.load_entries(out) == [e1, e2])
check("roudix: idempotent", core.build_config(out, [e1, e2]) == out)
check("roudix: tail intact", out.endswith("}\n") and "swapDevices = [ ];" in out)

# 3. remove one, then all
out2 = core.build_config(out, [e1])
check("remove one", core.load_entries(out2) == [e1] and "Games" not in out2)
out3 = core.build_config(out2, [])
check("remove all -> back to original", out3 == ROUDIX_HW)

# 4. adopt a foreign (nix-disk style) block outside the markers, keep exotic ones
foreign = ROUDIX_HW.rstrip()[:-1] + '''
  fileSystems."/media/old" = {
    device = "/dev/disk/by-uuid/9999";
    fsType = "ntfs";
    options = [ "defaults" "nofail" "uid=1000" ];
  };
  fileSystems."/mnt/share" = {
    device = "server:/export";
    fsType = "nfs";
  };
  fileSystems."/bind" = {
    device = "/home/x";
    fsType = "none";
    options = [ "bind" ];
    neededForBoot = true;
  };
}
'''
ents = core.load_entries(foreign)
check("foreign: only the by-uuid ntfs block adopted", [e.mountpoint for e in ents] == ["/media/old"])
res = core.build_config(foreign, ents)
check("foreign: nfs block untouched", 'fileSystems."/mnt/share"' in res and "server:/export" in res)
check("foreign: bind block untouched", "neededForBoot = true;" in res)
check("foreign: adopted block moved into managed region", res.index("# >>> roudix-disk") < res.index('"/media/old"'))
check("foreign: stable", core.build_config(res, core.load_entries(res)) == res)

# 5. comments / strings that look like blocks
tricky = ROUDIX_HW.rstrip()[:-1] + '''
  # fileSystems."/media/ghost" = { device = "/dev/disk/by-uuid/0"; fsType = "ext4"; };
  /* fileSystems."/media/ghost2" = { device = "/dev/disk/by-uuid/0"; fsType = "ext4"; }; */
  environment.etc."note".text = "fileSystems.\\"/media/ghost3\\" = { };";
}
'''
check("tricky: ghosts ignored", [b.mountpoint for b in core.parse_blocks(tricky)] == ["/", "/home", "/nix", "/boot"])

# 6. placeholder host (lib.mkDefault wrapper) parses and stays protected
nixie = '''{ lib, ... }:
{
  fileSystems."/" = lib.mkDefault {
    device = "/dev/disk/by-label/NIXOS_ROOT";
    fsType = "ext4";
  };
}
'''
b = core.parse_blocks(nixie)
check("nixie: mkDefault block parsed, protected, not adoptable", len(b) == 1 and not b[0].adoptable and b[0].device.endswith("NIXOS_ROOT"))

# 7. refusal of the attrset form
try:
    core.parse_blocks('{ fileSystems = { "/" = { device = "x"; }; }; }')
    check("attrset form refused", False)
except core.ConfigError:
    check("attrset form refused", True)

# 8. validation
V = core.validate_mountpoint
check("mp: /media/Data ok", V("/media/Data", []) is None)
check("mp: /home/me/Games ok", V("/home/me/Games", []) is None)
for bad in ["/", "/home", "/nix/store", "/boot/efi", "/etc/x", "media/x", "/media/a b", "/media/x/", "/media/../etc", '/media/"x', "/media/$x", "/var/log", "/tmp/x"]:
    check(f"mp: reject {bad!r}", V(bad, []) is not None)
check("mp: duplicate rejected", V("/media/Data", ["/media/Data"]) is not None)
try:
    core.build_config(ROUDIX_HW, [core.MountEntry('/media/x"; evil = "', "/dev/disk/by-uuid/1", "ext4", [])])
    check("injection in mountpoint refused", False)
except core.ConfigError:
    check("injection in mountpoint refused", True)
try:
    core.build_config(ROUDIX_HW, [core.MountEntry("/media/x", "/dev/disk/by-uuid/1", "ext4", ['x" ]; evil = [ "'])])
    check("injection in option refused", False)
except core.ConfigError:
    check("injection in option refused", True)

# 9. options / names
check("opts: ext4", core.default_options("ext4", False, 1000, 100) == ["defaults", "nofail", "x-gvfs-show"])
check("opts: btrfs ssd", "discard=async" in core.default_options("btrfs", False, 1, 1) and "compress=zstd:1" in core.default_options("btrfs", True, 1, 1))
check("opts: btrfs hdd has no ssd", "ssd" not in core.default_options("btrfs", True, 1, 1))
check("opts: ntfs3 uid/gid", "uid=1000" in core.default_options("ntfs3", False, 1000, 100))
check("fstype: ntfs -> ntfs3", core.nix_fstype("ntfs") == "ntfs3" and core.nix_fstype("ext4") == "ext4")
p = core.Partition("sdb1", "/dev/sdb1", 1, "ext4", "My Data!", "u")
