# 13. root helper, dry-run: every refusal happens BEFORE any command; happy path order is right
import io, contextlib
class _R:  # fake CompletedProcess
    def __init__(self, out=""): self.stdout, self.returncode = out, 0
def run_helper(argv, tree=None, uid="0"):
    calls = []
    fake_sub = types.SimpleNamespace(
        run=lambda cmd, **kw: (calls.append(cmd), _R("1234-ABCD\n"))[1],
        CalledProcessError=core.subprocess.CalledProcessError, PIPE=-1, STDOUT=-2)
    saved = (core.subprocess, core._sh, core._lsblk_json, os.path.exists)
    core.subprocess = fake_sub
    core._sh = lambda cmd: calls.append(cmd)
    core._lsblk_json = lambda *a: tree if tree is not None else {"blockdevices": [{"name": "sdz", "type": "disk", "mountpoints": [None], "children": []}]}
    os.path.exists = lambda p: True
    env_before = os.environ.get("PKEXEC_UID")
    if uid is None: os.environ.pop("PKEXEC_UID", None)
    else: os.environ["PKEXEC_UID"] = uid
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            rc = core.helper_format(argv)
    finally:
        core.subprocess, core._sh, core._lsblk_json, os.path.exists = saved
        if env_before is None: os.environ.pop("PKEXEC_UID", None)
        else: os.environ["PKEXEC_UID"] = env_before
    return rc, calls, buf.getvalue()

for name, argv, kw in [
    ("partition node", ["/dev/sdz1", "ext4", "Data"], {}),
    ("path trick", ["/dev/../etc/passwd", "ext4", "Data"], {}),
    ("shell trick", ["/dev/sdz; rm -rf /", "ext4", "Data"], {}),
    ("unsupported fs", ["/dev/sdz", "xfs", "Data"], {}),
    ("bad label", ["/dev/sdz", "ext4", "bad label"], {}),
    ("flag-looking label", ["/dev/sdz", "ext4", "-fvery-long-label-here"], {}),
    ("label starting with a dash", ["/dev/sdz", "ext4", "-f"], {}),
    ("missing PKEXEC_UID", ["/dev/sdz", "ext4", "Data"], {"uid": None}),
    ("wrong arg count", ["/dev/sdz", "ext4"], {}),
    ("mounted disk", ["/dev/sdz", "ext4", "Data"], {"tree": {"blockdevices": [{"name": "sdz", "type": "disk", "children": [{"name": "sdz1", "type": "part", "mountpoints": ["/media/x"]}]}]}}),
    ("root disk (LUKS grandchild on /)", ["/dev/sdz", "ext4", "Data"], {"tree": {"blockdevices": [{"name": "sdz", "type": "disk", "children": [{"name": "sdz1", "type": "part", "mountpoints": [None], "children": [{"name": "cr", "type": "crypt", "mountpoints": ["/"]}]}]}]}}),
    ("active swap", ["/dev/sdz", "ext4", "Data"], {"tree": {"blockdevices": [{"name": "sdz", "type": "disk", "children": [{"name": "sdz1", "type": "part", "mountpoints": ["[SWAP]"]}]}]}}),
    ("not a disk", ["/dev/sdz", "ext4", "Data"], {"tree": {"blockdevices": [{"name": "sdz", "type": "part", "mountpoints": [None]}]}}),
]:
    rc, calls, out = run_helper(argv, **kw)
    check(f"helper refuses: {name} (rc=2, zero commands)", rc == 2 and calls == [])

rc, calls, out = run_helper(["/dev/sdz", "ext4", "Data"])
