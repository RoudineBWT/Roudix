"""
Other operating systems found in the EFI NVRAM, offered as Limine entries.

What roudix-installer.sh did with `efibootmgr -v` (now in both the GTK and the terminal wizard):
list the firmware boot entries that are not Roudix / firmware tools, let the
user pick some, and write them into modules/system/boot/boot.local.nix as
`extraEntries` for Limine (chainload by partition PARTUUID + EFI path).

No GTK here. Everything that ends up in the generated file is validated: the
label comes from the firmware and is written inside a Nix ''…'' string.
"""
import re
from typing import NamedTuple

from roudix_installer.sysutil import run_maybe_root

# Entries that must not be offered: Roudix/NixOS itself and firmware tools.
_SKIP = re.compile(
    r"nixos|roudix|uefi|firmware|setup|shell|pxe|ipv4|ipv6|network|floppy|optical"
    r"|\bcd\b|dvd|usb boot",
    re.I,
)
# Boot0001* <label>\tHD(1,GPT,<partuuid>,0x800,0x100000)/File(\EFI\Microsoft\Boot\bootmgfw.efi)…
# (newer efivar prints /\EFI\… without File(…)); efibootmgr may append binary garbage after .efi.
_LINE = re.compile(r"^Boot[0-9A-Fa-f]{4}\*\s*(?P<label>.*?)\s*HD\((?P<hd>[^)]*)\)(?P<rest>.*)$")
_PARTUUID = re.compile(r"GPT,([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})")
_EFI_PATH = re.compile(r"((?:\\[^\s\\,()]+)+?\.efi)", re.I)
_SAFE_PATH = re.compile(r"^/[\w.+\-/]+\.efi$", re.I)
_UNSAFE_LABEL = re.compile(r"[^\w .+()\-/:]")


class BootEntry(NamedTuple):
    label: str
    partuuid: str
    efi_path: str


def parse(efibootmgr_output: str) -> list[BootEntry]:
    """BootEntry list from `efibootmgr -v` output (active entries only)."""
    entries: list[BootEntry] = []
    for line in efibootmgr_output.splitlines():
        m = _LINE.match(line.strip())
        if not m:
            continue
        label = re.sub(r"\s+", " ", _UNSAFE_LABEL.sub("", m.group("label"))).strip()
        if not label or _SKIP.search(label):
            continue
        uuid = _PARTUUID.search("GPT," + m.group("hd").split("GPT,", 1)[-1]) if "GPT," in m.group("hd") else None
        path = _EFI_PATH.search(m.group("rest"))
        if not uuid or not path:
            continue
        efi_path = path.group(1).replace("\\", "/")
        if not _SAFE_PATH.match(efi_path):
            continue
        entry = BootEntry(label, uuid.group(1).lower(), efi_path)
        if entry not in entries:
            entries.append(entry)
    return entries


def detect() -> list[BootEntry]:
    """Other systems in the firmware boot menu ([] when efibootmgr is missing,
    the machine booted in legacy BIOS mode, or nothing else is installed)."""
    return parse(run_maybe_root(["efibootmgr", "-v"]))


def render(entries) -> str:
    """Content of modules/system/boot/boot.local.nix for the chosen entries."""
    lines = [
        "# ── boot.local.nix ──────────────────────────────────────────────────────────",
        "# Generated by roudix-installer — gitignored, never overwritten by git pull.",
        "# ────────────────────────────────────────────────────────────────────────────",
        "{",
        "  extraEntries = ''",
        "    /+Other systems and bootloaders",
    ]
    for label, partuuid, efi_path in entries:
        if not (_SAFE_PATH.match(efi_path) and not _UNSAFE_LABEL.search(label)
                and re.fullmatch(r"[0-9a-fA-F-]{36}", partuuid)):
            raise ValueError(f"Refusing an unsafe boot entry: {label!r}")
        lines += [f"    //{label}", "      protocol: efi", f"      path: uuid({partuuid}):{efi_path}"]
    lines += ["  '';", "}", ""]
    return "\n".join(lines)
