#!/usr/bin/env python3
"""Generate the Roudix GNOME Shell themes from assets/palette/Roudix.json (the
single source of truth for Roudix colours):

  assets/gnome-shell/Roudix-Dark/gnome-shell/gnome-shell.css
  assets/gnome-shell/Roudix-Light/gnome-shell/gnome-shell.css

How it works: the real gnome-shell stylesheet sources (data/theme, SCSS) are
fetched at a pinned tag, their colour definitions (_colors.scss and
_default-colors.scss) are swapped for Roudix ones, and the result is compiled
with libsass — exactly what gnome-shell's own meson build does with sassc. All
layout / widget rules stay upstream, only the colours change, so the theme
tracks gnome-shell instead of being a hand-written fork.

The GNOME *accent colour* setting is deliberately ignored: `-st-accent-color`
and `-st-accent-fg-color` are replaced by Roudix's mPrimary / mOnPrimary, so
the shell stays Roudix-orange whatever accent is picked in Settings.

Requirements: git, plus either `pip install libsass` or the `sassc` binary
(nix shell nixpkgs#sassc).

Usage:
  python3 scripts/gen-gnome-shell-theme.py                   # tag 50.1
  python3 scripts/gen-gnome-shell-theme.py --tag 50.2        # other gnome-shell tag
  python3 scripts/gen-gnome-shell-theme.py --upstream DIR    # existing gnome-shell
                                                             #   checkout (data/theme inside)

The generated CSS derives from gnome-shell's stylesheet (GPL-2.0-or-later) —
see THIRD_PARTY.md.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE = ROOT / "assets/palette/Roudix.json"
OUT = ROOT / "assets/gnome-shell"
DEFAULT_TAG = "50.1"
CACHE = Path.home() / ".cache/roudix"


# ── colour helpers (hex in, hex out) ─────────────────────────────────────────

def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(c):
    return "#%02x%02x%02x" % tuple(c)


def mix(a, b, t):
    """a * (1 - t) + b * t, as hex."""
    return hexc(tuple(round(x * (1 - t) + y * t) for x, y in zip(rgb(a), rgb(b))))


# ── upstream sources ─────────────────────────────────────────────────────────

def fetch_upstream(tag):
    dest = CACHE / f"gnome-shell-{tag}"
    if (dest / "data/theme/gnome-shell-sass").is_dir():
        return dest / "data/theme"
    CACHE.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        shutil.rmtree(dest)
    print(f"fetching gnome-shell {tag} (data/theme only)…")
    run = lambda *a, **k: subprocess.run(a, check=True, **k)
    run("git", "-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1",
        "--filter=blob:none", "--sparse", "--branch", tag,
        "https://github.com/GNOME/gnome-shell.git", str(dest))
    run("git", "-C", str(dest), "sparse-checkout", "set", "data/theme")
    return dest / "data/theme"


# ── Roudix colour definitions (replace upstream _colors / _default-colors) ───

def colors_scss(p, d, dark):
    """p = palette of the variant being built, d = dark palette (the overview,
    OSD and lock screen are 'always dark' in GNOME, even in the light theme)."""
    t = p["terminal"]["normal"]
    if dark:
        base = mix(p["mSurface"], "#000000", 0.18)   # entries, inset areas
    else:
        base = mix(p["mSurface"], "#FFFFFF", 0.55)

    def hx(x):
        return x.lower()

    return f"""\
//
// Roudix colour definitions — GENERATED by scripts/gen-gnome-shell-theme.py
// from assets/palette/Roudix.json. Do not edit by hand.
//
@import '_palette.scss';

// Roudix palette ({'dark' if dark else 'light'} variant)
$roudix_accent:      {hx(p["mPrimary"])};   // mPrimary   (replaces -st-accent-color)
$roudix_accent_fg:   {hx(p["mOnPrimary"])};   // mOnPrimary (replaces -st-accent-fg-color)
$roudix_surface:     {hx(p["mSurface"])};
$roudix_surface_var: {hx(p["mSurfaceVariant"])};
$roudix_on_surface:  {hx(p["mOnSurface"])};
$roudix_outline:     {hx(p["mOutline"])};
$roudix_error:       {hx(p["mError"])};
$roudix_on_error:    {hx(p["mOnError"])};
$roudix_green:       {hx(t["green"])};
$roudix_yellow:      {hx(t["yellow"])};
$roudix_base:        {hx(base)};

// Always-dark system surfaces (overview, lock screen, OSD) use the dark palette.
$roudix_sys_base:    {hx(d["mSurface"])};
$roudix_sys_fg:      {hx(d["mOnSurface"])};

// ── upstream names ──────────────────────────────────────────────────────────
$_base_color_dark:  $roudix_sys_base;
$_base_color_light: $roudix_sys_fg;

// accent
$accent_color: if($variant == 'light', $roudix_accent, st-mix($roudix_accent, $roudix_on_surface, 60%));

// destructive / error
$destructive_bg_color: $roudix_error;
$destructive_fg_color: $roudix_on_error;
$destructive_color: $destructive_bg_color;
$error_bg_color: $roudix_error;
$error_fg_color: $roudix_on_error;
$error_color: $error_bg_color;

// success / warning (terminal green + yellow of the palette)
$success_bg_color: $roudix_green;
$success_fg_color: $roudix_accent_fg;
$success_color: $success_bg_color;
$warning_bg_color: $roudix_yellow;
$warning_fg_color: transparentize(black, .2);
$warning_color: $warning_bg_color;

// links
$link_color: if($variant == 'light', st-darken($roudix_accent, 10%), st-lighten($roudix_accent, 20%));
$link_visited_color: st-transparentize($link_color, .6);

$background_mix_factor: if($variant == 'light', 12%, 9%);

// shadows
$shadow_color: if($variant == 'light', rgba(0,0,0,.05), rgba(0,0,0,0.2));
$text_shadow_color: if($variant == 'light', rgba(255,255,255,0.3), rgba(0,0,0,0.2));

// border opacities
$border_opacity: if($variant == 'light', .85, .9);
$focus_border_opacity: .2;

@if $contrast == 'high' {{
    $border_opacity: .5;
    $focus_border_opacity: .1;
    $shadow_color: transparent;
    $text_shadow_color: transparent;
}}

// ── global colors ───────────────────────────────────────────────────────────
$base_color: $roudix_base;
$bg_color: if($variant == 'light', $roudix_surface, $roudix_surface_var);
$fg_color: $roudix_on_surface;

// OSD elements
$osd_fg_color: $roudix_sys_fg;
$osd_bg_color: lighten($roudix_sys_base, 5%);

// system elements (e.g. the overview) that are always dark
$system_base_color: $roudix_sys_base;
$system_fg_color: $roudix_sys_fg;

// panel
$panel_bg_color: $roudix_surface;
$panel_fg_color: $roudix_on_surface;
$panel_border_color: if($variant == 'light', transparentize($roudix_on_surface, .9), transparent);

// cards
$card_bg_color: if($variant == 'light', $roudix_base, lighten($bg_color, 7%));
$card_shadow_color: if($variant == 'light', transparentize(black, .97), transparent);
$card_shadow_border_color: if($variant == 'light', transparentize(black, .91), transparent);

//
// Derived colors
//
$borders_color: transparentize($fg_color, $border_opacity);
$outer_borders_color: mix($roudix_outline, $bg_color, 55%);

$osd_borders_color: transparentize($osd_fg_color, 0.9);
$osd_outer_borders_color: transparentize($osd_fg_color, 0.98);

$system_bg_color: lighten($system_base_color, 5%);
$system_borders_color: transparentize($system_fg_color, .9);
$system_insensitive_fg_color: mix($system_bg_color, $system_fg_color, 37%);
$system_overlay_bg_color: mix($system_base_color, $system_fg_color, 90%);

$insensitive_fg_color: if($variant == 'light', mix($fg_color, $bg_color, 60%), mix($fg_color, $bg_color, 50%));
$insensitive_bg_color: mix($bg_color, $base_color, 60%);
$insensitive_borders_color: mix($borders_color, $base_color, 60%);

$checked_bg_color: if($variant == 'light', darken($bg_color, 7%), lighten($bg_color, 7%));
$checked_fg_color: if($variant == 'light', darken($fg_color, 7%), lighten($fg_color, 7%));

$hover_bg_color: if($variant == 'light', darken($bg_color, 9%), lighten($bg_color, 10%));
$hover_fg_color: if($variant == 'light', darken($fg_color, 9%), lighten($fg_color, 10%));

$active_bg_color: if($variant == 'light', darken($bg_color, 11%), lighten($bg_color, 12%));
$active_fg_color: if($variant == 'light', darken($fg_color, 11%), lighten($fg_color, 12%));

$accent_borders_color: if($variant == 'light', st-darken($roudix_accent, 20%), st-lighten($roudix_accent, 30%));

$card_insensitive_fg_color: if($variant == 'light', darken($insensitive_fg_color, 5%), lighten($insensitive_fg_color, 9%));
"""


def build_variant(upstream, name, p, d, dark, tag):
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "theme"
        shutil.copytree(upstream, work)
        sass_dir = work / "gnome-shell-sass"

        # Bake the Roudix accent in place of the system-provided one.
        for f in sass_dir.rglob("*.scss"):
            s = f.read_text()
            s2 = s.replace("-st-accent-fg-color", "$roudix_accent_fg") \
                  .replace("-st-accent-color", "$roudix_accent")
            if s2 != s:
                f.write_text(s2)

        (sass_dir / "_colors.scss").write_text(colors_scss(p, d, dark))
        # Everything _default-colors.scss defined now lives in _colors.scss.
        (sass_dir / "_default-colors.scss").write_text("// merged into _colors.scss\n")

        entry = work / "roudix-entry.scss"
        entry.write_text(
            f"$variant: '{'dark' if dark else 'light'}';\n$contrast: 'normal';\n\n"
            '@import "gnome-shell-sass/_colors";\n'
            '@import "gnome-shell-sass/_drawing";\n'
            '@import "gnome-shell-sass/_common";\n'
            '@import "gnome-shell-sass/_widgets";\n'
        )
        css = compile_scss(entry)

    header = (
        "/* Roudix GNOME Shell theme — %s\n"
        " * GENERATED by scripts/gen-gnome-shell-theme.py from assets/palette/Roudix.json\n"
        " * on top of the gnome-shell %s stylesheet (GPL-2.0-or-later). Do not edit by hand.\n"
        " */\n" % (name, tag)
    )
    return header + css


def compile_scss(entry):
    try:
        import sass  # libsass
        return sass.compile(filename=str(entry), output_style="expanded")
    except ImportError:
        pass
    if shutil.which("sassc"):
        return subprocess.run(["sassc", "-t", "expanded", str(entry)],
                              check=True, capture_output=True, text=True).stdout
    sys.exit("need a Sass compiler: `pip install libsass` or `nix shell nixpkgs#sassc`")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tag", default=DEFAULT_TAG, help="gnome-shell tag (default %(default)s)")
    ap.add_argument("--upstream", type=Path, help="gnome-shell checkout (contains data/theme)")
    args = ap.parse_args()

    upstream = (args.upstream / "data/theme") if args.upstream else fetch_upstream(args.tag)
    pal = json.loads(PALETTE.read_text())

    for variant, dark in (("dark", True), ("light", False)):
        name = f"Roudix-{variant.capitalize()}"
        css = build_variant(upstream, name, pal[variant], pal["dark"], dark, args.tag)
        out = OUT / name / "gnome-shell/gnome-shell.css"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(css)
        print(f"wrote {out.relative_to(ROOT)}  ({len(css) // 1024} KiB)")


if __name__ == "__main__":
    main()
